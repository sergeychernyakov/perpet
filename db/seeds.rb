  create_ads
  attach_catalog_photos
  create_my_ads
  create_articles
  create_faq
  create_support_channels
  puts "Готово: #{Ad.count} объявлений, #{Article.count} статей, #{FaqItem.count} вопросов, #{SupportChannel.count} канала поддержки."
