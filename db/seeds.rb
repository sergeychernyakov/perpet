      - Уберите все опасности. Спрячьте висящие провода, бытовую химию, мелкие предметы, которые можно проглотить, и токсичные комнатные растения: лилии, например, крайне ядовиты для кошек.
      - Создайте укрытие. У животного должна быть легальная «тихая гавань», откуда его никто не будет насильно доставать. Это может быть переноска с открытой дверцей, картонная коробка или пространство под диваном.

      ## Первые часы в новом доме: правило «Не трогай»

      Самая частая ошибка — окружать животное чрезмерным вниманием, тискать его и пытаться развеселить.

      Игнорируйте питомца в хорошем смысле: занимайтесь своими делами, говорите спокойным, тихим голосом. Животное быстрее успокоится, если увидит, что двуногий обитатель спокоен и не проявляет к нему агрессивного или навязчивого интереса.

      - Для кошек. Поставьте переноску в приготовленной комнате, откройте дверцу и отойдите. Не вытряхивайте кошку силой. Пусть она сидит внутри столько, сколько нужно: кошка должна выйти сама, когда поймет, что в комнате тихо и никто на нее не охотится.
      - Для собак. Сразу по приезде не ведите собаку в квартиру — сначала погуляйте с ней минут 20 вокруг дома. Пусть она сделает свои дела и немного сбросит предстартовый стресс. Переступив порог дома, спокойно покажите ей миску с водой и ее место.

      ## Запах дома

      Животные живут в мире запахов. Стерильно чистая квартира для них — как белая глухая комната для человека.

      - Если вы берете питомца на передержку, обязательно попросите у хозяев его родную лежанку, нестираный плед или даже старую футболку владельца. Запах родного человека на временном месте творит чудеса и снижает тревогу в разы.
      - Если вы взяли животное из приюта или питомника, попросите тряпочку или игрушку, которая пахнет его мамой или вольером.

      ## Режим дня — основа стабильности

      В состоянии стресса животному жизненно необходима рутина. Если процессы предсказуемы, значит, мир вокруг безопасен.

      - Кормите питомца строго в одно и то же время, которое было у него в прошлой жизни.
      - Для собак сохраняйте привычный график выгула.
      - Не меняйте рацион! Адаптация — худшее время для кулинарных экспериментов. Кормите тем же кормом, что и раньше, чтобы к психологическому стрессу не добавилось расстройство желудка.

      ## Первые 3–7 дней на новом месте

      - Животное отказывается от еды. Нормально, если кошка или собака не едят в первые сутки. Предлагайте еду, но не настаивайте. Для аппетита можно предложить ароматный влажный паштет. Если голодовка длится более двух суток — стоит проконсультироваться с ветеринаром.
      - Промахи мимо лотка, туалет в неположенном месте. Из-за стресса и незнакомых запахов животное может «потерять» туалет. Ни в коем случае не ругайте и не тыкайте носом — это лишь усугубит страх. Спокойно уберите с использованием специального спрея, уничтожающего запах мочи (без аммиака!), и поставьте лоток поближе к тому месту, где питомец проводит больше всего времени.
      - Питомец постоянно прячется. Не выковыривайте кошку из-за шкафа. Просто поставьте еду, воду и лоток поблизости и оставьте ее в покое. Она выйдет ночью, когда все лягут спать, чтобы разведать обстановку.

