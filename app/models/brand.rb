# сервиса, поэтому живёт в коде рядом с промо-карточками.
class Brand
  Facet = Data.define(:title, :text)
  Value = Data.define(:title, :text)

  SUMMARY = "Компания по передержке животных, которая обьединяет людей вокруг общей " \
