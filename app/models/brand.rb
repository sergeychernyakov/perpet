      Value.new(title: "Доверие",
                text: "Вы сможете всегда просмотреть отзывы по пользователям и договориться о личной " \
                      "встрече перед оказанием самих услуг. Также у нас есть юридическая страница " \
                      "и круглосуточная поддержка."),
      Value.new(title: "Доступность",
